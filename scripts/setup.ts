/**
 * One-command project setup against YOUR Supabase project.
 *
 *   npm run setup            → checks env, applies migrations, loads seed data, creates demo accounts
 *   npm run setup -- --yes   → same, without the confirmation prompt
 *
 * Safe to re-run: each migration is skipped when it is already applied, seed.sql
 * only runs when the demo patients are missing, and the demo seed is idempotent.
 * It never drops tables or deletes non-demo data.
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { createInterface } from "node:readline/promises";
import path from "node:path";
import pg from "pg";
import { appendEnv, loadEnv } from "./lib/env-file";

const ENV_FILE = ".env.local";
const YES = process.argv.includes("--yes");

const ok = (m: string) => console.log(`  ✓ ${m}`);
const info = (m: string) => console.log(`  → ${m}`);
const fail = (m: string): never => {
  console.error(`\n  ✗ ${m}\n`);
  process.exit(1);
};

/** Sentinel object per migration: if it exists, the migration has been applied. */
const SENTINELS: Record<string, string> = {
  "20261031000000_schema.sql": "select to_regclass('public.profiles') is not null as applied",
  "20261031000100_queue_engine.sql": "select to_regprocedure('public.queue_transition(uuid,text,integer,text)') is not null as applied",
  "20261031000200_booking.sql": "select to_regprocedure('public.book_appointment(timestamptz,public.visit_reason,text,text)') is not null as applied",
  "20261031000300_admin.sql": "select to_regprocedure('public.save_working_days(jsonb)') is not null as applied",
  "20261031000400_whatsapp_channel.sql":
    "select exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid where t.typname = 'notification_channel' and e.enumlabel = 'whatsapp_link') as applied",
  "20261031000500_whatsapp.sql": "select to_regprocedure('public.mark_notification_opened(uuid)') is not null as applied",
};

async function main() {
  console.log("\nDr. Rodaina Medhat Clinic setup\n");
  if (!existsSync(ENV_FILE)) fail(`${ENV_FILE} not found. Copy .env.example to ${ENV_FILE} and fill in your Supabase values.`);
  const env = loadEnv(ENV_FILE);

  // 1. Required values the user must provide.
  const missing: string[] = [];
  if (!env.NEXT_PUBLIC_SUPABASE_URL) missing.push("NEXT_PUBLIC_SUPABASE_URL  (Supabase → Project Settings → API → Project URL)");
  if (!env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY && !env.NEXT_PUBLIC_SUPABASE_ANON_KEY)
    missing.push("NEXT_PUBLIC_SUPABASE_ANON_KEY  (Supabase → Project Settings → API Keys → anon / publishable)");
  if (!env.SUPABASE_SERVICE_ROLE_KEY) missing.push("SUPABASE_SERVICE_ROLE_KEY  (Supabase → Project Settings → API Keys → service_role / secret. Server only, never NEXT_PUBLIC_)");
  if (!env.DATABASE_URL) missing.push("DATABASE_URL  (Supabase → Connect → Session pooler connection string, with your database password)");
  if (missing.length) fail(`Add these to ${ENV_FILE}, then run npm run setup again:\n\n    ${missing.join("\n    ")}`);
  if (Object.keys(env).some((k) => k.startsWith("NEXT_PUBLIC_") && /SERVICE|SECRET/.test(k)))
    fail("A secret is exposed through a NEXT_PUBLIC_ variable. Rename it so it never reaches the browser.");

  const ref = new URL(env.NEXT_PUBLIC_SUPABASE_URL!).hostname.split(".")[0];
  if (!env.DATABASE_URL!.includes(ref!)) info(`Warning: DATABASE_URL does not mention project ${ref}. Make sure both point to the same project.`);
  ok(`Supabase project ${ref}`);

  // 2. Generate local secrets and demo passwords that are still missing.
  const generated: Record<string, string> = {};
  const secret = () => randomBytes(32).toString("base64url");
  const password = () => `Demo-${randomBytes(6).toString("base64url")}9`;
  if (!env.CRON_SECRET) generated.CRON_SECRET = secret();
  if (!env.OTP_PEPPER) generated.OTP_PEPPER = secret();
  if (!env.DEMO_DOCTOR_EMAIL) generated.DEMO_DOCTOR_EMAIL = "doctor@mosa3da.app";
  if (!env.DEMO_SECRETARY_EMAIL) generated.DEMO_SECRETARY_EMAIL = "secretary@mosa3da.app";
  if (!env.DEMO_DOCTOR_PASSWORD) generated.DEMO_DOCTOR_PASSWORD = password();
  if (!env.DEMO_SECRETARY_PASSWORD) generated.DEMO_SECRETARY_PASSWORD = password();
  if (!env.DEMO_PATIENT_PASSWORD) generated.DEMO_PATIENT_PASSWORD = password();
  if (Object.keys(generated).length) {
    appendEnv(ENV_FILE, generated, `Generated by npm run setup on ${new Date().toISOString()}`);
    Object.assign(env, generated);
    Object.assign(process.env, generated);
    ok(`Added ${Object.keys(generated).join(", ")} to ${ENV_FILE}`);
  }

  // 3. Confirm the target.
  const host = new URL(env.DATABASE_URL!.replace(/^postgres(ql)?:/, "http:")).hostname;
  if (!YES) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const answer = await rl.question(`\n  This will apply migrations and demo data to ${host}. Continue? (y/N) `);
    rl.close();
    if (!/^y(es)?$/i.test(answer.trim())) fail("Cancelled.");
  }

  // 4. Connect.
  // node-postgres treats sslmode=require as verify-full, which rejects Supabase's pooler
  // certificate chain. Keep TLS on, without CA pinning (POC); sslmode=disable is kept for local DBs.
  const dbUrl = new URL(env.DATABASE_URL!);
  const sslDisabled = dbUrl.searchParams.get("sslmode") === "disable";
  dbUrl.searchParams.delete("sslmode");
  const client = new pg.Client({
    connectionString: dbUrl.toString(),
    ssl: sslDisabled ? false : { rejectUnauthorized: false },
    connectionTimeoutMillis: 15_000,
  });
  try {
    await client.connect();
  } catch (e) {
    const msg = e instanceof Error ? e.message : String(e);
    if (/ENOTFOUND|ENETUNREACH|EHOSTUNREACH|ETIMEDOUT|timeout/i.test(msg) && host.startsWith("db."))
      fail(
        `Could not reach ${host} (${msg}).\n    The direct connection is IPv6-only on many networks. In Supabase click "Connect" → "Session pooler",\n    copy that URL (host *.pooler.supabase.com, port 5432) into DATABASE_URL and run setup again.`,
      );
    if (/password authentication failed/i.test(msg)) fail("Wrong database password in DATABASE_URL (Supabase → Project Settings → Database → Reset password).");
    fail(`Database connection failed: ${msg}`);
  }
  ok(`Connected to ${host}`);

  const { rows: authCheck } = await client.query("select to_regclass('auth.users') is not null as ok");
  if (!authCheck[0].ok) fail("This database has no auth.users table. DATABASE_URL must point to a Supabase project.");

  // 5. Migrations.
  const dir = path.join("supabase", "migrations");
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()) {
    const sentinel = SENTINELS[file];
    if (sentinel) {
      const { rows } = await client.query(sentinel);
      if (rows[0].applied) {
        ok(`${file} (already applied)`);
        continue;
      }
    }
    info(`Applying ${file}`);
    try {
      await client.query(readFileSync(path.join(dir, file), "utf8"));
    } catch (e) {
      await client.query("rollback").catch(() => undefined);
      fail(`${file} failed: ${e instanceof Error ? e.message : e}`);
    }
    ok(`${file}`);
  }

  // Make the REST API pick up new tables/functions right away.
  await client.query("notify pgrst, 'reload schema'").catch(() => undefined);

  // 6. Reference data (working hours + demo patients) only on first run.
  const { rows: demo } = await client.query("select count(*)::int as n from public.patients where normalized_phone = '+201001234561'");
  if (demo[0].n === 0) {
    info("Loading supabase/seed.sql");
    await client.query(readFileSync(path.join("supabase", "seed.sql"), "utf8"));
    ok("Working hours, clinic settings and 10 demo patients");
  } else {
    ok("Seed data already present");
  }
  await client.end();

  // 7. Demo accounts, appointments and today's queue (uses the Admin API).
  info("Creating demo accounts and today's queue");
  const run = spawnSync(process.execPath, [path.join("node_modules", "tsx", "dist", "cli.mjs"), path.join("scripts", "seed-demo.ts")], {
    stdio: "inherit",
    env: { ...process.env, ...env },
  });
  if (run.status !== 0) fail("Demo seed failed (see the error above).");

  console.log(`
  ✓ Setup complete

  Start the app:   npm run dev     →  http://localhost:3000
  Check it:        npm run smoke   (in a second terminal, while the app is running)

  Doctor:      ${env.DEMO_DOCTOR_EMAIL}   /  ${env.DEMO_DOCTOR_PASSWORD}
  Secretary:   ${env.DEMO_SECRETARY_EMAIL}   /  ${env.DEMO_SECRETARY_PASSWORD}
  Patient:     010 0123 4561   /  ${env.DEMO_PATIENT_PASSWORD}   (sign in at /patient/login)
`);
}

main().catch((e) => fail(e instanceof Error ? e.message : String(e)));
